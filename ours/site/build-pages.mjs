function sitemap() {
  const urls = ['/', HUB_PATH, ...trades.map((t) => `${HUB_PATH}${t.slug}/`)];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- OURS: generated by ours/site/build-pages.mjs -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${ORIGIN}${u}</loc><lastmod>${LASTMOD}</lastmod></url>`).join('\n')}
</urlset>
`;
}

function write(rel, content) {
  const file = join(PUBLIC, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log('wrote', rel);
}

write('social-media-for/index.html', hubPage());
for (const t of trades) write(`social-media-for/${t.slug}/index.html`, tradePage(t));
write('sitemap.xml', sitemap());
