function crumbs(items) {
  const html = items
    .map(([name, path], i) =>
      i === items.length - 1
        ? `<li><span aria-current="page">${esc(name)}</span></li>`
        : `<li><a href="${path}">${esc(name)}</a></li>`,
    )
    .join('');
  const data = {
    '@type': 'BreadcrumbList',
    itemListElement: items.map(([name, path], i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name,
      item: ORIGIN + path,
    })),
  };
  return { html: `<nav class="crumbs" aria-label="Breadcrumb"><ol>${html}</ol></nav>`, data };
}

